// Writes src/app/build-info.ts with the version and commit this build comes
// from, shown at the bottom of the sign-in page. Runs before every start,
// build and test (see package.json).
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const git = (args) => {
  try {
    return execSync(`git ${args}`, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
};

// git@github.com:owner/repo.git and https://github.com/owner/repo.git both
// become https://github.com/owner/repo.
const repoUrl = git('remote get-url origin')
  .replace(/^git@github\.com:/, 'https://github.com/')
  .replace(/\.git$/, '');

const info = {
  version: JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version,
  commit: git('rev-parse --short HEAD') || 'unknown',
  commitUrl: repoUrl && git('rev-parse HEAD') ? `${repoUrl}/commit/${git('rev-parse HEAD')}` : '',
  commitSubject: git('log -1 --pretty=%s'),
  commitDate: git('log -1 --pretty=%cI'),
  branch: git('rev-parse --abbrev-ref HEAD') || 'unknown',
  dirty: git('status --porcelain') !== '',
  builtAt: new Date().toISOString(),
};

writeFileSync(
  new URL('../src/app/build-info.ts', import.meta.url),
  `// Generated by scripts/build-info.mjs, do not edit.\nexport const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;\n`,
);
